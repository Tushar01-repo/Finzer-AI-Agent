from __future__ import annotations

from typing import Any

from app.clients.embedding_router import EmbeddingRouter
from app.config.settings import settings
from app.repositories.database import PostgresDatabase


class DocumentRetriever:
    """
    Vector similarity retriever for document chunks.

    Flow:
        query
          -> EmbeddingRouter
          -> query embedding
          -> PostgreSQL / pgvector cosine similarity
          -> top-k document chunks

    Important:
    Retrieval is restricted to embeddings generated by the exact
    provider/model selected by the current EmbeddingRouter session.
    """

    def __init__(
        self,
        *,
        database: PostgresDatabase | None = None,
        embedding_client: EmbeddingRouter | None = None,
    ):
        self.database = database or PostgresDatabase()

        self.embedding_client = (
            embedding_client or EmbeddingRouter()
        )

        self.embedding_provider = (
            self.embedding_client.provider
        )

        self.embedding_model = (
            self.embedding_client.model
        )

        self.embedding_dimension = (
            settings.EMBEDDING_DIMENSION
        )

        if self.embedding_dimension <= 0:
            raise ValueError(
                "EMBEDDING_DIMENSION must be greater than zero."
            )

    @staticmethod
    def _vector_literal(
        embedding: list[float],
    ) -> str:
        """
        Convert a Python embedding into pgvector literal format.

        Example:
            [0.1, 0.2, 0.3]
        """

        return (
            "["
            + ",".join(str(float(value)) for value in embedding)
            + "]"
        )

    def retrieve(
        self,
        query: str,
        *,
        document_key: str,
        top_k: int = 5,
    ) -> list[dict[str, Any]]:
        """
        Retrieve the most similar chunks from one document.
        """

        query = query.strip()
        document_key = document_key.strip()

        if not query:
            raise ValueError(
                "query cannot be empty."
            )

        if not document_key:
            raise ValueError(
                "document_key cannot be empty."
            )

        if top_k <= 0:
            raise ValueError(
                "top_k must be greater than zero."
            )

        # ---------------------------------------------------------
        # Generate query embedding
        # ---------------------------------------------------------

        query_embedding = self.embedding_client.embed(
            query
        )

        if len(query_embedding) != self.embedding_dimension:
            raise ValueError(
                "Unexpected query embedding dimension: "
                f"expected={self.embedding_dimension}, "
                f"actual={len(query_embedding)}"
            )

        vector_literal = self._vector_literal(
            query_embedding
        )

        # ---------------------------------------------------------
        # Similarity search
        #
        # pgvector:
        #
        #   <=> = cosine distance
        #
        # similarity = 1 - cosine_distance
        # ---------------------------------------------------------

        sql = """
            SELECT
                d.document_id,
                d.document_key,

                dc.chunk_id,
                dc.chunk_index,
                dc.content_type,
                dc.content,

                dc.page_start,
                dc.page_end,

                dc.section,
                dc.subsection,
                dc.heading,

                dc.token_count,

                dce.provider,
                dce.model,
                dce.dimension,

                1 - (
                    dce.embedding <=> %s::vector
                ) AS similarity

            FROM document_chunk_embeddings dce

            JOIN document_chunks dc
                ON dc.chunk_id = dce.chunk_id

            JOIN documents d
                ON d.document_id = dc.document_id

            WHERE d.document_key = %s
              AND dce.provider = %s
              AND dce.model = %s
              AND dce.dimension = %s

            ORDER BY
                dce.embedding <=> %s::vector

            LIMIT %s;
        """

        params = (
            vector_literal,
            document_key,
            self.embedding_provider,
            self.embedding_model,
            self.embedding_dimension,
            vector_literal,
            top_k,
        )

        with self.database.connect() as connection:
            with connection.cursor() as cursor:
                cursor.execute(
                    sql,
                    params,
                )

                rows = cursor.fetchall()

                columns = [
                    description.name
                    for description
                    in cursor.description
                ]

        results = [
            dict(zip(columns, row))
            for row in rows
        ]

        # psycopg / PostgreSQL may return Decimal for similarity.
        for result in results:
            similarity = result.get("similarity")

            if similarity is not None:
                result["similarity"] = float(
                    similarity
                )

        return results