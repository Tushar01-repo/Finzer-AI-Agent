from __future__ import annotations

from datetime import datetime
from typing import Any

from app.clients.embedding_router import EmbeddingRouter
from app.config.settings import settings
from app.repositories.database import PostgresDatabase


class NewsRetriever:
    """
    Semantic retriever for analyzed and embedded financial news.

    Retrieval flow:
        query
          -> query embedding
          -> article_embeddings cosine similarity
          -> articles metadata join
          -> optional company/date filters
          -> ranked article evidence

    The retriever only compares vectors generated by the same
    embedding provider, model, and dimension as the current
    EmbeddingRouter session.
    """

    def __init__(
        self,
        database: PostgresDatabase | None = None,
        embedding_client: EmbeddingRouter | None = None,
    ) -> None:
        self.database = database or PostgresDatabase()
        self.embedding_client = embedding_client or EmbeddingRouter()

        self.embedding_provider = self.embedding_client.provider
        self.embedding_model = self.embedding_client.model
        self.embedding_dimension = settings.EMBEDDING_DIMENSION

        if self.embedding_dimension <= 0:
            raise ValueError(
                "EMBEDDING_DIMENSION must be greater than zero."
            )

    def retrieve(
        self,
        query: str,
        *,
        top_k: int = 5,
        company: str | None = None,
        published_after: datetime | None = None,
        published_before: datetime | None = None,
    ) -> list[dict[str, Any]]:
        """
        Retrieve semantically relevant financial news.

        Args:
            query:
                Natural-language retrieval query.

            top_k:
                Maximum number of articles returned.

            company:
                Optional company/entity filter. Matches entries stored
                in articles.companies_mentioned.

            published_after:
                Optional inclusive lower publication-time bound.

            published_before:
                Optional inclusive upper publication-time bound.

        Returns:
            Ranked list of article evidence dictionaries.
        """

        query = query.strip()

        if not query:
            raise ValueError("query cannot be empty.")

        if top_k <= 0:
            raise ValueError(
                "top_k must be greater than zero."
            )

        if top_k > 50:
            raise ValueError(
                "top_k cannot be greater than 50."
            )

        normalized_company = None

        if company is not None:
            normalized_company = company.strip()

            if not normalized_company:
                raise ValueError(
                    "company cannot be empty when provided."
                )

        query_embedding = self.embedding_client.embed(query)

        if len(query_embedding) != self.embedding_dimension:
            raise ValueError(
                "Unexpected query embedding dimension: "
                f"expected {self.embedding_dimension}, "
                f"got {len(query_embedding)}."
            )

        vector_literal = (
            "["
            + ",".join(
                str(float(value))
                for value in query_embedding
            )
            + "]"
        )

        conditions = [
            "ae.embedding_provider = %s",
            "ae.embedding_model = %s",
            "ae.embedding_dimension = %s",
            "a.processing_status = 'embedded'",
        ]

        params: list[Any] = [
            vector_literal,
            self.embedding_provider,
            self.embedding_model,
            self.embedding_dimension,
        ]

        if normalized_company is not None:
            conditions.append(
                """
                EXISTS (
                    SELECT 1
                    FROM jsonb_array_elements_text(
                        COALESCE(
                            a.companies_mentioned,
                            '[]'::jsonb
                        )
                    ) AS company_name
                    WHERE LOWER(company_name)
                          = LOWER(%s)
                )
                """
            )

            params.append(normalized_company)

        if published_after is not None:
            conditions.append(
                "a.published_at >= %s"
            )
            params.append(published_after)

        if published_before is not None:
            conditions.append(
                "a.published_at <= %s"
            )
            params.append(published_before)

        params.append(top_k)

        where_clause = "\nAND ".join(
            condition.strip()
            for condition in conditions
        )

        sql = f"""
            SELECT
                a.article_key,
                a.title,
                a.url,
                a.source,
                a.authors,
                a.published_at,
                a.summary,
                a.key_facts,
                a.companies_mentioned,
                a.market_impact,
                a.relevance_score,
                a.relevance_reason,
                ae.embedding_provider,
                ae.embedding_model,
                ae.embedding_dimension,
                ae.embedded_at,

                1 - (
                    ae.embedding
                    <=> %s::vector
                ) AS similarity

            FROM article_embeddings ae

            INNER JOIN articles a
                ON a.article_key = ae.article_key

            WHERE
                {where_clause}

            ORDER BY
                ae.embedding <=> %s::vector

            LIMIT %s
        """

        # The query vector is used twice:
        #   1. SELECT similarity
        #   2. ORDER BY cosine distance
        #
        # Insert the second vector before LIMIT.
        execution_params = (
            params[:-1]
            + [vector_literal]
            + [params[-1]]
        )

        with self.database.connect() as connection:
            with connection.cursor() as cursor:
                cursor.execute(
                    sql,
                    tuple(execution_params),
                )

                rows = cursor.fetchall()

        results: list[dict[str, Any]] = []

        for rank, row in enumerate(
            rows,
            start=1,
        ):
            results.append(
                {
                    "retrieval_rank": rank,
                    "article_key": row[0],
                    "title": row[1],
                    "url": row[2],
                    "source": row[3],
                    "authors": row[4] or [],
                    "published_at": row[5],
                    "summary": row[6],
                    "key_facts": row[7] or [],
                    "companies_mentioned": row[8] or [],
                    "market_impact": row[9],
                    "relevance_score": (
                        float(row[10])
                        if row[10] is not None
                        else None
                    ),
                    "relevance_reason": row[11],
                    "embedding_provider": row[12],
                    "embedding_model": row[13],
                    "embedding_dimension": row[14],
                    "embedded_at": row[15],
                    "similarity": (
                        float(row[16])
                        if row[16] is not None
                        else None
                    ),
                }
            )

        return results