-- ============================================================
-- Finzer AI
-- Document / IPO ingestion schema
--
-- Creates:
--   1. documents
--   2. document_chunks
--   3. document_chunk_embeddings
--
-- Existing article tables are intentionally untouched.
-- ============================================================


-- ------------------------------------------------------------
-- pgvector
-- ------------------------------------------------------------

CREATE EXTENSION IF NOT EXISTS vector;


-- ============================================================
-- 1. DOCUMENTS
-- ============================================================

CREATE TABLE IF NOT EXISTS documents (
    document_id BIGSERIAL PRIMARY KEY,

    -- Stable application-level identity.
    -- Initially generated from:
    --
    -- SHA256(source + normalized_pdf_url)
    --
    -- This prevents rediscovering the same source document from
    -- creating duplicate document records.
    document_key VARCHAR(64) NOT NULL UNIQUE,

    source VARCHAR(100) NOT NULL,

    company_name TEXT,

    document_type VARCHAR(100),

    -- Original title exactly as discovered from the source.
    source_title TEXT NOT NULL,

    filing_url TEXT,

    pdf_url TEXT,

    file_name TEXT,

    file_sha256 VARCHAR(64),

    file_size_bytes BIGINT,

    published_at TIMESTAMPTZ,

    -- Discovery/download/parsing lifecycle.
    status VARCHAR(50) NOT NULL DEFAULT 'discovered',

    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT documents_status_check
        CHECK (
            status IN (
                'discovered',
                'downloading',
                'downloaded',
                'parsing',
                'parsed',
                'chunked',
                'embedding',
                'embedded',
                'failed'
            )
        )
);


-- ------------------------------------------------------------
-- Useful document indexes
-- ------------------------------------------------------------

CREATE INDEX IF NOT EXISTS idx_documents_source
    ON documents(source);

CREATE INDEX IF NOT EXISTS idx_documents_company_name
    ON documents(company_name);

CREATE INDEX IF NOT EXISTS idx_documents_document_type
    ON documents(document_type);

CREATE INDEX IF NOT EXISTS idx_documents_status
    ON documents(status);

CREATE INDEX IF NOT EXISTS idx_documents_published_at
    ON documents(published_at DESC);

CREATE INDEX IF NOT EXISTS idx_documents_file_sha256
    ON documents(file_sha256)
    WHERE file_sha256 IS NOT NULL;


-- ============================================================
-- 2. DOCUMENT CHUNKS
-- ============================================================

CREATE TABLE IF NOT EXISTS document_chunks (
    chunk_id BIGSERIAL PRIMARY KEY,

    document_id BIGINT NOT NULL,

    -- Sequential position generated by DocumentChunker.
    chunk_index INTEGER NOT NULL,

    -- TEXT or TABLE
    content_type VARCHAR(20) NOT NULL,

    content TEXT NOT NULL,

    page_start INTEGER NOT NULL,

    page_end INTEGER NOT NULL,

    section TEXT,

    subsection TEXT,

    heading TEXT,

    token_count INTEGER NOT NULL,

    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_document_chunks_document
        FOREIGN KEY (document_id)
        REFERENCES documents(document_id)
        ON DELETE CASCADE,

    CONSTRAINT document_chunks_content_type_check
        CHECK (
            content_type IN (
                'text',
                'table'
            )
        ),

    CONSTRAINT document_chunks_page_check
        CHECK (
            page_start > 0
            AND page_end >= page_start
        ),

    CONSTRAINT document_chunks_token_count_check
        CHECK (
            token_count >= 0
        ),

    CONSTRAINT uq_document_chunk_index
        UNIQUE (
            document_id,
            chunk_index
        )
);


-- ------------------------------------------------------------
-- Chunk indexes
-- ------------------------------------------------------------

CREATE INDEX IF NOT EXISTS idx_document_chunks_document_id
    ON document_chunks(document_id);

CREATE INDEX IF NOT EXISTS idx_document_chunks_content_type
    ON document_chunks(content_type);

CREATE INDEX IF NOT EXISTS idx_document_chunks_section
    ON document_chunks(document_id, section);

CREATE INDEX IF NOT EXISTS idx_document_chunks_pages
    ON document_chunks(
        document_id,
        page_start,
        page_end
    );


-- ============================================================
-- 3. DOCUMENT CHUNK EMBEDDINGS
-- ============================================================

CREATE TABLE IF NOT EXISTS document_chunk_embeddings (
    embedding_id BIGSERIAL PRIMARY KEY,

    chunk_id BIGINT NOT NULL,

    provider VARCHAR(50) NOT NULL,

    model VARCHAR(255) NOT NULL,

    dimension INTEGER NOT NULL,

    -- Current Finzer embedding dimension.
    embedding VECTOR(1024) NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_document_chunk_embeddings_chunk
        FOREIGN KEY (chunk_id)
        REFERENCES document_chunks(chunk_id)
        ON DELETE CASCADE,

    CONSTRAINT document_chunk_embeddings_dimension_check
        CHECK (
            dimension = 1024
        ),

    -- Prevent accidentally embedding the same chunk twice using
    -- the same provider/model.
    CONSTRAINT uq_document_chunk_embedding_model
        UNIQUE (
            chunk_id,
            provider,
            model
        )
);


-- ------------------------------------------------------------
-- Embedding indexes
-- ------------------------------------------------------------

CREATE INDEX IF NOT EXISTS idx_document_chunk_embeddings_chunk_id
    ON document_chunk_embeddings(chunk_id);

CREATE INDEX IF NOT EXISTS idx_document_chunk_embeddings_provider_model
    ON document_chunk_embeddings(
        provider,
        model
    );


-- ============================================================
-- updated_at helper
-- ============================================================

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;


DROP TRIGGER IF EXISTS trg_documents_updated_at
    ON documents;


CREATE TRIGGER trg_documents_updated_at
BEFORE UPDATE ON documents
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();